"""
Data for testing spin-polarized (UHF) calculations.

Reference values obtained with tblite 0.7.0 (accuracy 1, Broyden mixing with
damping 0.4, electronic temperature 300 K). The UHF references without
spin-polarization interaction (``*_uhf``) correspond to tblite's two-channel
calculation with a spin-polarization scale of zero.

Charges are given in the charge/magnetization representation, i.e., the first
channel contains the total partial charges and the second channel contains
the (negative) magnetization, ``q_beta - q_alpha``.
"""

from __future__ import annotations

import torch
from tad_mctc.data.molecules import merge_nested_dicts, mols

from dxtb._src.typing import Molecule, Tensor, TypedDict


class Refs(TypedDict, total=False):
    """
    Format of reference records containing GFN1-xTB and GFN2-xTB reference
    values. Not all systems contain references for both methods.
    """

    charge: Tensor
    """Total charge of the molecule."""

    spin: Tensor
    """Number of unpaired electrons."""

    egfn1: Tensor
    """Total energy for spin-polarized GFN1-xTB."""

    egfn1_uhf: Tensor
    """Total energy for GFN1-xTB (UHF, no spin polarization)."""

    egfn2: Tensor
    """Total energy for spin-polarized GFN2-xTB."""

    egfn2_uhf: Tensor
    """Total energy for GFN2-xTB (UHF, no spin polarization)."""

    qgfn1: Tensor
    """Atomic charge/magnetization for spin-polarized GFN1-xTB."""

    qgfn1_uhf: Tensor
    """Atomic charge/magnetization for GFN1-xTB (UHF)."""

    qgfn2: Tensor
    """Atomic charge/magnetization for spin-polarized GFN2-xTB."""

    qgfn2_uhf: Tensor
    """Atomic charge/magnetization for GFN2-xTB (UHF)."""

    qshgfn1: Tensor
    """Shell charge/magnetization for spin-polarized GFN1-xTB."""

    qshgfn2: Tensor
    """Shell charge/magnetization for spin-polarized GFN2-xTB."""

    dpgfn2: Tensor
    """Atomic dipole moments (charge/magnetization) for spin-polarized GFN2."""

    qpgfn2: Tensor
    """Atomic quadrupole moments (charge/magnetization) for spin-pol. GFN2."""

    wbogfn1: Tensor
    """Wiberg/Mayer bond orders (charge/magnetization) for spin-pol. GFN1."""


class Record(Molecule, Refs):
    """Store for molecular information and reference values."""


